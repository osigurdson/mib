"""Import pinned upstream highlight colors; development-only, requires Neovim.

Usage: python3 tools/import-colors.py /path/to/theme-checkouts
The directory must contain tokyonight, catppuccin, kanagawa and everforest repos.
Normal builds use the checked-in header and need no Lua/Neovim/network access.
"""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

root = Path(__file__).resolve().parent.parent
sources = {
    "tokyonight": ("https://github.com/folke/tokyonight.nvim", "cdc07ac78467a233fd62c493de29a17e0cf2b2b6"),
    "catppuccin": ("https://github.com/catppuccin/nvim", "edefef779ab08ce1a4a404713e3012b0d202bd35"),
    "kanagawa": ("https://github.com/rebelot/kanagawa.nvim", "bb85e4bfc8d89b0e62c8fa53ccdd13d12e2f77b3"),
    "everforest": ("https://github.com/sainnhe/everforest", "85a86eb62409e3ec88713bff3d1b9d7374e112e4"),
}
export = r'''
local scheme, background = vim.env.JOT_SCHEME, vim.env.JOT_BACKGROUND
vim.opt.runtimepath:prepend(vim.env.JOT_THEME_ROOT .. "/" .. scheme)
vim.o.termguicolors = true
vim.o.background = background
local variant = scheme
if scheme == "tokyonight" then
  variant = "tokyonight-" .. (background == "dark" and "night" or "day")
elseif scheme == "catppuccin" then
  require("catppuccin").setup({ auto_integrations = false })
  variant = "catppuccin-" .. (background == "dark" and "mocha" or "latte")
elseif scheme == "kanagawa" then
  variant = "kanagawa-" .. (background == "dark" and "wave" or "lotus")
else
  vim.g.everforest_background = "medium"
end
vim.cmd.colorscheme(variant)
local function hl(name) return vim.api.nvim_get_hl(0, {name = name, link = false, create = false}) end
local normal = hl("Normal")
assert(normal.fg and normal.bg, "Normal must have explicit RGB colors")
local groups = {}
for _, name in ipairs({"Normal", "LineNr", "Underlined", "Title", "Comment", "Special",
                       "CursorLine", "Search", "Visual", "Cursor", "StatusLine", "Pmenu", "PmenuSel"}) do
  local value = hl(name)
  local fg, bg = value.fg or normal.fg, value.bg or normal.bg
  if value.reverse then fg, bg = bg, fg end
  groups[name] = {string.format("#%06x", fg), string.format("#%06x", bg)}
end
for _, name in ipairs({"markdownLinkText", "@markup.link", "@markup.link.url", "Underlined", "Title"}) do
  local value = hl(name)
  if value.fg then
    groups.Link = {string.format("#%06x", value.fg), string.format("#%06x", normal.bg)}
    break
  end
end
assert(groups.Link, "Link accent must have an RGB color")
vim.fn.writefile({vim.json.encode({scheme = scheme, background = background, groups = groups})}, vim.env.JOT_OUTPUT)
'''

def blend(a, b, weight):
    a, b = int(a[1:], 16), int(b[1:], 16)
    return "#" + "".join(f"{(((a >> shift) & 255) * (100-weight) + ((b >> shift) & 255) * weight) // 100:02x}" for shift in (16, 8, 0))

if len(sys.argv) != 2:
    raise SystemExit(__doc__)
checkouts = Path(sys.argv[1]).resolve()
for name, (_, revision) in sources.items():
    actual = subprocess.check_output(["git", "-C", str(checkouts / name), "rev-parse", "HEAD"], text=True).strip()
    if actual != revision:
        raise SystemExit(f"{name}: expected {revision}, found {actual}")

header = "#ifndef JOT_THEME_PALETTES_H\n#define JOT_THEME_PALETTES_H\n/* Generated by tools/import-colors.py. See docs/colors.md and third_party licenses.\n"
for name, (url, revision) in sources.items():
    header += f" * {name}: {url}/tree/{revision}\n"
header += " */\n"
records = []
with tempfile.TemporaryDirectory(prefix="jot-import-colors-") as directory:
    temp = Path(directory)
    script, output = temp / "export.lua", temp / "colors.json"
    script.write_text(export)
    for name in sources:
        for background in ("dark", "light"):
            environment = dict(os.environ, JOT_SCHEME=name, JOT_BACKGROUND=background,
                               JOT_THEME_ROOT=str(checkouts), JOT_OUTPUT=str(output),
                               XDG_CACHE_HOME=str(temp / "cache"), XDG_DATA_HOME=str(temp / "data"),
                               XDG_STATE_HOME=str(temp / "state"))
            subprocess.run(["nvim", "--headless", "-u", "NONE", "-n", "-l", str(script)], env=environment, check=True)
            record = json.loads(output.read_text())
            records.append(record)
            g = record["groups"]
            fg, bg = g["Normal"]
            code = g["CursorLine"][1]
            if code == bg:
                code = blend(bg, fg, 7)
            colors = [bg, fg, g["LineNr"][0], g["Link"][0], g["Title"][0],
                      g["Comment"][0], g["Comment"][0], g["Special"][0], code,
                      g["Search"][1], g["Visual"][1], g["Cursor"][1], g["StatusLine"][1],
                      g["Pmenu"][1], g["PmenuSel"][1], fg, blend(bg, fg, 4), blend(bg, fg, 17),
                      blend(bg, fg, 10), blend(bg, fg, 17), g["Search"][0], g["Visual"][0],
                      g["StatusLine"][0], g["Pmenu"][0], g["PmenuSel"][0]]
            if colors[11] == bg:
                colors[11] = fg
            header += f"static const struct palette theme_{name}_{background} = {{\n"
            for i in range(0, len(colors), 5):
                header += "    " + ", ".join("0xff" + color[1:] for color in colors[i:i+5]) + ",\n"
            header += "};\n"
(root / "src/theme-palettes.h").write_text(header + "#endif\n")
# The optional export is useful for checking fixtures against upstream colors.
if os.environ.get("JOT_PALETTE_JSON"):
    Path(os.environ["JOT_PALETTE_JSON"]).write_text(json.dumps(records, indent=2) + "\n")
